def participants():
    return execute('SELECT * FROM participantes ORDER BY nombre', fetch=True)

def selector(df, key):
    if df.empty:
        st.info('Primero registre un participante.')
        return None
    opts = {f"{r['codigo']} · {r['nombre']}": int(r['id']) for _,r in df.iterrows()}
    selected = st.selectbox('Participante', list(opts), key=key)
    return opts[selected]

def template_download(cols, filename, label):
    data = pd.DataFrame(columns=cols)
    from io import BytesIO
    b=BytesIO()
    with pd.ExcelWriter(b, engine='openpyxl') as writer:
        data.to_excel(writer, index=False)
    st.download_button(label, b.getvalue(), file_name=filename,
                       mime='application/vnd.openxmlformats-officedocument.spreadsheetml.sheet')

def optional_float(v):
    if pd.isna(v) or str(v).strip()=='': return None
    return float(v)

def import_rows(uploaded, required, fn):
    if uploaded is None: return
    try:
        df = pd.read_excel(uploaded, dtype={'codigo':str})
        missing=[c for c in required if c not in df.columns]
        if missing:
            st.error('Faltan columnas: '+', '.join(missing)); return
        st.dataframe(df.head(10), hide_index=True)
        if st.button('Confirmar importación', key='confirm_'+str(required)):
            ok=0; errs=[]
            for i,row in df.iterrows():
                try:
                    fn(row);ok+=1
                except Exception as e:
                    errs.append(f'Fila {i+2}: {e}')
            st.success(f'{ok} filas importadas.')
            if errs: st.error('\n'.join(errs[:15]))
            st.rerun()
    except Exception as e:
        st.error(f'No se pudo leer Excel: {e}')

